// Writes lua/arktype/casefold.lua: the classes of characters V8 treats as equal
// under a regex's `iu` flags, which ErrorLens compiles every replace matcher
// with. Each class is computed by V8 itself rather than read from a Unicode
// table, so the Lua matcher folds exactly as the JS engine running it does.
//
// Every class with more than one member contains a cased character or one that
// changes when case mapped or folded (V8's ICU doesn't always flag both members
// of a pair, e.g. U+0390 and U+1FD3 aren't CWCF), and every member is a letter,
// mark, letter number or symbol, so matching each such character against all
// of those finds every class.
import { writeFileSync } from "node:fs"
import { join } from "node:path"

const outFile = join(
	import.meta.dirname,
	"..",
	"lua",
	"arktype",
	"casefold.lua"
)

const pool: number[] = []
const foldable: number[] = []
const inPool = /[\p{L}\p{M}\p{Nl}\p{So}\p{Cased}\p{CWCM}\p{CWCF}]/u
const mayFold = /[\p{Cased}\p{CWCM}\p{CWCF}]/u

for (let cp = 0; cp <= 0x10ffff; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue
	const char = String.fromCodePoint(cp)
	if (!inPool.test(char)) continue
	pool.push(cp)
	if (mayFold.test(char)) foldable.push(cp)
}

const poolString = pool.map(cp => String.fromCodePoint(cp)).join("")
const parent = new Map<number, number>()

const find = (cp: number): number => {
	let root = cp
	while (parent.has(root) && parent.get(root) !== root) root = parent.get(root)!
	return root
}

const union = (a: number, b: number) => {
	const rootA = find(a)
	const rootB = find(b)
	if (rootA === rootB) return
	if (rootA < rootB) parent.set(rootB, rootA)
	else parent.set(rootA, rootB)
}

for (const cp of foldable) {
	const matcher = new RegExp(`\\u{${cp.toString(16)}}`, "giu")
	for (const match of poolString.matchAll(matcher)) {
		const other = match[0].codePointAt(0)!
		if (other !== cp) union(cp, other)
	}
}

const classes = new Map<number, number[]>()
for (const cp of parent.keys()) {
	const root = find(cp)
	if (!classes.has(root)) classes.set(root, [root])
	if (cp !== root) classes.get(root)!.push(cp)
}

const roots = [...classes.keys()].sort((a, b) => a - b)
const hex = (cp: number) => `0x${cp.toString(16).toUpperCase()}`

const canonLines: string[] = []
const memberLines: string[] = []
for (const root of roots) {
	const members = classes.get(root)!.sort((a, b) => a - b)
	for (const member of members)
		if (member !== root) canonLines.push(`\t[${hex(member)}] = ${hex(root)},`)
	memberLines.push(`\t[${hex(root)}] = { ${members.map(hex).join(", ")} },`)
}

writeFileSync(
	outFile,
	`-- Generated by scripts/writeCasefold.ts on Node ${process.versions.node} (V8 ${process.versions.v8},
-- Unicode ${process.versions.unicode}). Do not edit.
--
-- canon[cp] is the lowest code point V8 treats as equal to cp under a regex's
-- "iu" flags (absent when that's cp itself); members[canon] lists every code
-- point in its class.
local canon = {
${canonLines.join("\n")}
}

local members = {
${memberLines.join("\n")}
}

return { canon = canon, members = members }
`
)

console.log(`wrote ${roots.length} case-insensitive classes to ${outFile}`)
